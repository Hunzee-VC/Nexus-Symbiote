"""Render ``docs/reference/cli.md`` from the ``nexus-symbiote`` Click command tree.

The page records what ``nexus-symbiote <command> --help`` prints for every command
and subcommand at a fixed terminal width, so the committed reference can be checked
against the code. ``--write`` updates the page; ``--check`` prints a unified diff and
exits 1 when the committed page is stale; with neither flag the page is printed.
"""

from __future__ import annotations

import argparse
import difflib
import sys
from collections.abc import Iterator, Sequence
from pathlib import Path

import click

from nexus_symbiote.cli import main as root_command

PROGRAM = "nexus-symbiote"
TERMINAL_WIDTH = 100
REPOSITORY_ROOT = Path(__file__).resolve().parent.parent
DEFAULT_PAGE = REPOSITORY_ROOT / "docs" / "reference" / "cli.md"
GENERATED_NOTICE = (
    "<!-- Generated by scripts/generate_cli_reference.py from the Click command tree. "
    "Do not edit by hand. -->"
)
INTRODUCTION = """\
This page is generated from the command definitions in `nexus_symbiote.cli` and its
registered command modules. Each section reproduces what `nexus-symbiote <command> --help`
prints, rendered at a terminal width of 100 columns; a narrower terminal wraps the same
text differently. The installed version's own `--help` output is authoritative where the
two differ, because this page describes the `main` branch.

Regenerate the page after changing a command:

```sh
python scripts/generate_cli_reference.py --write
```

`python scripts/generate_cli_reference.py --check` prints a diff and exits 1 when the page
is stale. `tests/test_cli_reference.py` makes the same comparison in the test suite.

Exit codes, policy files and command workflows are described in the
[quick start](../getting-started/quickstart.md) and
[configuration](../getting-started/configuration.md) pages.
"""


def iter_commands(
    command: click.Command, context: click.Context
) -> Iterator[tuple[click.Command, click.Context]]:
    """Yield every command with a context whose ``command_path`` names it."""
    yield command, context
    if isinstance(command, click.Group):
        for name in command.list_commands(context):
            child = command.get_command(context, name)
            if child is None:
                raise RuntimeError(f"{context.command_path}: unresolved subcommand {name}")
            child_context = click.Context(
                child, info_name=name, parent=context, terminal_width=TERMINAL_WIDTH
            )
            yield from iter_commands(child, child_context)


def anchor(heading: str) -> str:
    """Approximate GitHub's heading slug for the command headings used here."""
    slug = []
    for character in heading.lower():
        if character.isalnum() or character == "-":
            slug.append(character)
        elif character == " ":
            slug.append("-")
    return "".join(slug)


def summary(command: click.Command) -> str:
    """Return the first paragraph of the command's help text on one line."""
    text = (command.help or "").strip()
    first_paragraph = text.split("\n\n", 1)[0]
    return " ".join(first_paragraph.split())


def render() -> str:
    """Render the complete Markdown page."""
    root_context = click.Context(root_command, info_name=PROGRAM, terminal_width=TERMINAL_WIDTH)
    entries = list(iter_commands(root_command, root_context))
    lines = ["# CLI reference", "", GENERATED_NOTICE, "", INTRODUCTION.rstrip("\n"), ""]
    lines.extend(["## Contents", ""])
    for _, context in entries:
        path = context.command_path
        lines.append(f"- [`{path}`](#{anchor(path)})")
    for command, context in entries:
        path = context.command_path
        lines.extend(["", f"## `{path}`", ""])
        description = summary(command)
        if description:
            lines.extend([description, ""])
        lines.extend(["```text", command.get_help(context).rstrip("\n"), "```"])
    return "\n".join(lines) + "\n"


def check(page: Path, rendered: str) -> int:
    """Print a unified diff and return 1 when ``page`` differs from ``rendered``."""
    current = page.read_text(encoding="utf-8") if page.exists() else ""
    if current == rendered:
        return 0
    diff = difflib.unified_diff(
        current.splitlines(keepends=True),
        rendered.splitlines(keepends=True),
        fromfile=str(page),
        tofile="rendered",
    )
    sys.stdout.writelines(diff)
    print(f"\n{page} is stale; run: python scripts/generate_cli_reference.py --write")
    return 1


def main(argv: Sequence[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n", 1)[0])
    mode = parser.add_mutually_exclusive_group()
    mode.add_argument("--write", action="store_true", help="write the rendered page")
    mode.add_argument(
        "--check", action="store_true", help="exit 1 with a diff when the page is stale"
    )
    parser.add_argument(
        "--output",
        type=Path,
        default=DEFAULT_PAGE,
        help=f"page path (default: {DEFAULT_PAGE.relative_to(REPOSITORY_ROOT)})",
    )
    arguments = parser.parse_args(argv)
    rendered = render()
    if arguments.check:
        return check(arguments.output, rendered)
    if arguments.write:
        arguments.output.parent.mkdir(parents=True, exist_ok=True)
        arguments.output.write_text(rendered, encoding="utf-8")
        print(f"wrote {arguments.output}")
        return 0
    sys.stdout.write(rendered)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
