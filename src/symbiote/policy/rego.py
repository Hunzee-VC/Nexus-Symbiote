"""Rego export (``symbiote policy export-rego DIR``; ``spec/checks.md`` section 5).

Generates ``package agentbom`` (Rego v1 syntax) over the companion document: ``input`` is the camelCase AgentBOM
JSON. Each rule adds finding objects to ``data.agentbom.findings`` with the same ``checkId``, ``severity`` and
``subjectRefs`` the built-in engine produces, so OPA, Conftest and gateways that embed OPA can enforce the same
policy as ``symbiote policy check``.

Only checks whose Python logic is a plain predicate over the document are exported. Checks that need graph
reachability, three-valued reasoning, a baseline or an ordered client decision table (the lethal trifecta,
approval-gate resolution, drift against an approved snapshot) stay built-in. ``manifest.json`` lists both sets,
so a partial bundle is never mistaken for full coverage. Rego rules never report ``pass`` or ``indeterminate``:
a missing finding means only that the rule did not fire.
"""

