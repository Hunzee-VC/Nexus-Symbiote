def render_module() -> str:
    """The complete ``agentbom.rego`` module: shared helpers, then one block per exported check, sorted by id."""
    parts = [_HEADER.format(version=__version__)]
    for check_id in sorted(REGO_RULES):
        spec = CHECKS.get(check_id)
        title = spec.title if spec is not None else check_id
        parts.append(f"# {check_id}: {title}\n{REGO_RULES[check_id]}\n")
    parts.append(_FOOTER)
    return "\n".join(parts)


def export_rego(directory: Path) -> dict[str, object]:
    """Write ``agentbom.rego`` and ``manifest.json`` into ``directory`` and return the manifest."""
    directory.mkdir(parents=True, exist_ok=True)
    (directory / "agentbom.rego").write_text(render_module(), encoding="utf-8")
    manifest: dict[str, object] = {
        "package": "agentbom",
        "query": QUERY,
        "symbioteVersion": __version__,
        "input": "application/vnd.agentbom+json (companion document)",
        "rego": sorted(REGO_RULES),
        "builtinOnly": sorted(set(CHECKS) - set(REGO_RULES)),
        "note": (
            "Checks under builtinOnly need graph reachability, three-valued reasoning, a baseline or an ordered "
            "client decision table; run `symbiote policy check` for full coverage. Rego rules never report pass "
            "or indeterminate."
        ),
    }
    (directory / "manifest.json").write_text(
        json.dumps(manifest, indent=2, sort_keys=True) + "\n", encoding="utf-8"
    )
    return manifest


class RegoError(RuntimeError):
    """OPA is not installed, the policy directory is unusable, or evaluation failed."""


def evaluate_with_opa(
    bom: AgentBOM, policy_dir: Path, *, opa: str | None = None, timeout_s: int = 300
) -> tuple[list[Finding], list[str]]:
    """Evaluate ``data.agentbom.findings`` from the Rego in ``policy_dir`` over ``bom`` with the ``opa`` binary.

    Organisation rules may use their own ids (``ORG-001``); each finding needs ``checkId``, ``severity`` and
    ``subjectRefs``. Malformed findings are skipped and reported as warnings, never silently dropped. Raises
    :class:`RegoError` when OPA is missing, times out or exits non-zero.
    """
    from symbiote.export.companion import companion_bytes

    binary = opa or shutil.which("opa")
    if binary is None:
        raise RegoError("the `opa` binary is not on PATH (https://www.openpolicyagent.org/docs)")
    if not policy_dir.is_dir():
        raise RegoError(f"{policy_dir}: not a directory")
    with tempfile.TemporaryDirectory(prefix="symbiote-rego-") as tmp:
        document = Path(tmp) / "agentbom.json"
        document.write_bytes(companion_bytes(bom, validate=False))
        command = [
            binary,
            "eval",
            "--format",
            "json",
            "--data",
            str(policy_dir),
            "--input",
            str(document),
            QUERY,
        ]
        try:
            proc = subprocess.run(  # noqa: S603 - fixed argv, no shell; the caller chose the policy directory
                command, capture_output=True, text=True, timeout=timeout_s, check=False
            )
        except subprocess.TimeoutExpired:
            raise RegoError(f"opa eval did not finish within {timeout_s}s") from None
        except OSError as exc:
            raise RegoError(f"could not run opa: {exc}") from None
    if proc.returncode != 0:
        raise RegoError(f"opa eval failed: {proc.stderr.strip()[:800]}")
    try:
        results = json.loads(proc.stdout).get("result") or []
        values = results[0]["expressions"][0]["value"] if results else []
    except (ValueError, LookupError, AttributeError, TypeError):
        raise RegoError("opa eval output is not a findings set") from None
    findings: list[Finding] = []
    warnings: list[str] = []
    for raw in values if isinstance(values, list) else []:
        try:
            findings.append(
                Finding(
                    check_id=str(raw["checkId"]),
                    severity=str(raw["severity"]).lower(),
                    state=FindingState.FAIL,
                    subject_refs=list(raw.get("subjectRefs") or []),
                    message=str(raw.get("message") or raw["checkId"]),
                    locator=f"rego:{policy_dir.name}",
                )
            )
        except (KeyError, TypeError, AttributeError, ValidationError) as exc:
            warnings.append(f"ignored a malformed Rego finding ({type(exc).__name__}): {str(raw)[:160]}")
    return findings, warnings
